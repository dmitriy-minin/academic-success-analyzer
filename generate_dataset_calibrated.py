def clamp(v: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, v))

def calc_target_grade(
    avg_grade: float,
    grade_trend: float,
    num_absences: int,
    unexcused_absences: int,
    num_tardies: int,
    num_tests_completed: int,
    avg_test_attempts: float,
    num_assignments_submitted: int,
    max_tests: int = 15,
    max_assignments: int = 16,
) -> float:
    """
    Рассчитывает объективную итоговую оценку на основе академического среднего балла
    с учетом дисциплины, динамики и полноты выполнения программы.
    """
    # База: текущий средний балл определяет уровень (шкалу) оценки
    score = avg_grade

    # 1. Тренд (прогресс добавляет до +3.5 баллов, регресс снижает до -3.5 баллов)
    score += clamp(0.18 * grade_trend, -4.5, 4.5)

    # 2. Штраф за пропуски занятий
    excused = max(0, num_absences - unexcused_absences)
    absence_penalty = 0.25 * excused + 0.65 * unexcused_absences
    score -= clamp(absence_penalty, 0.0, 16.0)

    # 3. Штраф за опоздания
    score -= clamp(0.25 * num_tardies, 0.0, 3.0)

    # 4. Полнота сдачи тестов (если сданы все/почти все тесты — бонус, если есть хвосты — штраф)
    test_ratio = num_tests_completed / float(max_tests)
    if test_ratio >= 0.85:
        score += 1.5
    elif test_ratio < 0.60:
        score -= (0.60 - test_ratio) * 12.0

    # 5. Качество сдачи тестов (попытки)
    score += clamp((1.8 - avg_test_attempts) * 1.5, -2.5, 2.0)

    # 6. Полнота сдачи практических заданий
    assign_ratio = num_assignments_submitted / float(max_assignments)
    if assign_ratio >= 0.85:
        score += 1.5
    elif assign_ratio < 0.60:
        score -= (0.60 - assign_ratio) * 15.0

    # Итоговое ограничение: оценка не может выходить за [0, 100]
    return clamp(round(score, 1), 0.0, 100.0)


