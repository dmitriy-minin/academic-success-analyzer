FEATURE_NAMES = [
    "num_grades",
    "avg_grade",
    "grade_trend",
    "num_absences",
    "unexcused_absences",
    "num_tardies",
    "num_tests_completed",
    "avg_time_on_tests",
    "avg_test_attempts",
    "num_assignments_submitted",
    "avg_time_on_assignments",
    "target_grade",
]

def main():
    assert len(STUDENTS_DATA) == 122, f"Expected 122 records, got {len(STUDENTS_DATA)}"

    rows = []
    for s in STUDENTS_DATA:
        row = dict(zip(FEATURE_NAMES, s))
        rows.append(row)

    for filename in [OUTPUT_FILE, BACKUP_FILE]:
        with open(filename, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=FEATURE_NAMES)
            writer.writeheader()
            writer.writerows(rows)
        print(f"[OK] File '{filename}' successfully saved ({len(rows)} students).")

    # Сводка
    targets = [r["target_grade"] for r in rows]
    avg_grades = [r["avg_grade"] for r in rows]
    absences = [r["num_absences"] for r in rows]

    print("\n--- Manual Realistic College Dataset Summary (122 students, 72h) ---")
    print(f"Target Grade (target_grade):")
    print(f"  Min  : {min(targets):.1f}")
    print(f"  Max  : {max(targets):.1f}")
    print(f"  Mean : {sum(targets)/len(targets):.1f}")
    print(f"Current Avg Grade (avg_grade): {sum(avg_grades)/len(avg_grades):.1f}")
    print(f"Average Absences: {sum(absences)/len(absences):.1f} pairs (out of 36)")

    c_5 = sum(1 for g in targets if g >= 85.0)
    c_4 = sum(1 for g in targets if 70.0 <= g < 85.0)
    c_3 = sum(1 for g in targets if 55.0 <= g < 70.0)
    c_2 = sum(1 for g in targets if g < 55.0)

    print("\nAcademic Performance Distribution:")
    print(f"  Grade 5 (Excellent, 85-100) : {c_5:2d} students ({c_5/len(targets)*100:.1f}%)")
    print(f"  Grade 4 (Good, 70-84.9)     : {c_4:2d} students ({c_4/len(targets)*100:.1f}%)")
    print(f"  Grade 3 (Satisfactory, 55-69): {c_3:2d} students ({c_3/len(targets)*100:.1f}%)")
    print(f"  Grade 2 / Risk (< 55)       : {c_2:2d} students ({c_2/len(targets)*100:.1f}%)")

if __name__ == "__main__":
    main()
